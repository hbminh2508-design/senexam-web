-- ==============================================================================
-- SUPABASE MIGRATION: QUẢN LÝ QUỸ LỚP ME2 & ĐỐI SOÁT THANH TOÁN (SENEXAM)
-- ==============================================================================

-- 1. BẢNG QUẢN LÝ ĐỢT THU QUỸ (class_funds)
CREATE TABLE IF NOT EXISTS public.class_funds (
    id TEXT PRIMARY KEY,                                     -- VD: 'me2-hk2-2026'
    title TEXT NOT NULL,                                     -- Tiêu đề đợt quỹ
    class_name TEXT NOT NULL DEFAULT 'ME2',                  -- Tên lớp (ME2)
    amount_per_person NUMERIC NOT NULL DEFAULT 0,            -- Mức nộp cố định / bạn
    due_date TEXT,                                           -- Hạn nộp (YYYY-MM-DD hoặc ISO)
    bank_name TEXT NOT NULL,                                 -- Tên ngân hàng nhận (VietABank, MB...)
    bank_account TEXT NOT NULL,                              -- Số tài khoản nhận
    account_name TEXT NOT NULL,                              -- Tên chủ tài khoản nhận
    description TEXT,                                        -- Mục đích thu & metadata
    admin_passcode TEXT,                                     -- Mã bảo mật của Thủ Quỹ đợt này
    initial_balance NUMERIC DEFAULT 0,                       -- Số tiền ban đầu của lớp
    students JSONB DEFAULT '[]'::jsonb,                      -- Danh sách sinh viên & trạng thái nộp, minh chứng
    expenses JSONB DEFAULT '[]'::jsonb,                      -- Danh sách hóa đơn / bill chi tiêu trừ quỹ
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Bật tính năng Row Level Security (RLS)
ALTER TABLE public.class_funds ENABLE ROW LEVEL SECURITY;

-- 2. BẢNG QUẢN LÝ ĐƠN THANH TOÁN & MINH CHỨNG (class_fund_payments)
CREATE TABLE IF NOT EXISTS public.class_fund_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fund_id TEXT REFERENCES public.class_funds(id) ON DELETE CASCADE,
    student_id TEXT NOT NULL,
    student_name TEXT NOT NULL,
    mssv TEXT,
    order_code TEXT NOT NULL UNIQUE,                         -- Mã nộp duy nhất (VD: ME2-AN-1001)
    amount_vnd NUMERIC NOT NULL,                             -- Số tiền nộp
    status TEXT NOT NULL DEFAULT 'pending',                  -- 'pending', 'paid', 'expired'
    proof_image TEXT,                                        -- Ảnh chụp minh chứng chuyển khoản (Base64/URL)
    sepay_id TEXT,                                           -- ID giao dịch ngân hàng từ Webhook SePay
    raw_webhook JSONB,                                       -- Dữ liệu webhook nhận từ ngân hàng
    paid_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- Bật tính năng Row Level Security (RLS)
ALTER TABLE public.class_fund_payments ENABLE ROW LEVEL SECURITY;

-- 3. TẠO CÁC INDEX TĂNG TỐC TRUY VẤN
CREATE INDEX IF NOT EXISTS idx_class_funds_class_name ON public.class_funds(class_name);
CREATE INDEX IF NOT EXISTS idx_class_funds_created_at ON public.class_funds(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_class_fund_payments_fund_id ON public.class_fund_payments(fund_id);
CREATE INDEX IF NOT EXISTS idx_class_fund_payments_order_code ON public.class_fund_payments(order_code);
CREATE INDEX IF NOT EXISTS idx_class_fund_payments_student_id ON public.class_fund_payments(student_id);
CREATE INDEX IF NOT EXISTS idx_class_fund_payments_status ON public.class_fund_payments(status);

-- 4. CHÍNH SÁCH BẢO MẬT (RLS POLICIES)
-- Cho phép đọc công khai danh sách quỹ và các khoản chi minh bạch
DROP POLICY IF EXISTS "Public read class_funds" ON public.class_funds;
CREATE POLICY "Public read class_funds" ON public.class_funds
    FOR SELECT TO anon, authenticated, service_role USING (true);

DROP POLICY IF EXISTS "Allow manage class_funds" ON public.class_funds;
CREATE POLICY "Allow manage class_funds" ON public.class_funds
    FOR ALL TO anon, authenticated, service_role USING (true) WITH CHECK (true);

-- Cho phép đọc & ghi nhận đơn thanh toán và ảnh minh chứng
DROP POLICY IF EXISTS "Public read class_fund_payments" ON public.class_fund_payments;
CREATE POLICY "Public read class_fund_payments" ON public.class_fund_payments
    FOR SELECT TO anon, authenticated, service_role USING (true);

DROP POLICY IF EXISTS "Allow manage class_fund_payments" ON public.class_fund_payments;
CREATE POLICY "Allow manage class_fund_payments" ON public.class_fund_payments
    FOR ALL TO anon, authenticated, service_role USING (true) WITH CHECK (true);
